function showAddItem(){

    document.getElementById("addForm").style.display="block";
    document.getElementById("searchArea").style.display="none";

}


function hideAddItem(){

    document.getElementById("addForm").style.display="none";

}


function showSearch(){

    document.getElementById("searchArea").style.display="block";
    document.getElementById("addForm").style.display="none";

}


function addNewItem(){

    let name =
        document.getElementById("itemName").value.trim();

    let category =
        document.getElementById("itemCategory").value;

    let condition =
        document.getElementById("itemCondition").value;

    let location =
        document.getElementById("itemLocation").value.trim();

    let description =
        document.getElementById("itemDescription").value.trim();

    let contact =
        document.getElementById("itemContact").value.trim();

    let sharing =
        document.getElementById("itemSharing").value;


    if(
        name === "" ||
        location === "" ||
        description === "" ||
        contact === ""
    ){

        alert("Please fill all details.");
        return;

    }


    data.push({

        name:name,
        category:category,
        condition:condition,
        location:location,
        description:description,
        contact:contact,
        sharing:sharing,

        image:
        "https://images.unsplash.com/photo-1517842645767-c639042777db?w=700"

    });


    alert("Resource added successfully!");


    document.getElementById("itemName").value="";
    document.getElementById("itemLocation").value="";
    document.getElementById("itemDescription").value="";
    document.getElementById("itemContact").value="";


    hideAddItem();

    displayResources();

}


function displayResources(){

    let box =
        document.getElementById("resourceBox");


    let searchInput =
        document.getElementById("searchInput");

    let categoryFilter =
        document.getElementById("categoryFilter");


    let search =
        searchInput ? searchInput.value.toLowerCase() : "";


    let category =
        categoryFilter ? categoryFilter.value : "All";


    let filtered = data.filter(item => {

        let matchesSearch =

            item.name.toLowerCase().includes(search)

            ||

            item.category.toLowerCase().includes(search);


        let matchesCategory =

            category === "All"

            ||

            item.category === category;


        return matchesSearch && matchesCategory;

    });


    box.innerHTML="";


    document.getElementById("resourceCount").innerText =
        filtered.length + " Items";


    if(filtered.length === 0){

        box.innerHTML = `

            <div class="no-result">

                <h3>No Resource Found</h3>

                <p>
                    Try searching for another item.
                </p>

            </div>

        `;

        return;

    }


    filtered.forEach(item => {

        box.innerHTML += `

        <div class="card">

            <img
                src="${item.image}"
                alt="${item.name}"
            >

            <div class="card-content">

                <span class="badge">
                    ${item.category}
                </span>

                <h3>
                    ${item.name}
                </h3>

                <p>
                    <strong>Condition:</strong>
                    ${item.condition}
                </p>

                <p>
                    <strong>Location:</strong>
                    ${item.location}
                </p>

                <p>
                    <strong>Description:</strong>
                    ${item.description}
                </p>

                <p>
                    <strong>Sharing:</strong>
                    ${item.sharing}
                </p>

                <p>
                    <strong>Contact:</strong>
                    ${item.contact}
                </p>

                <button
                    class="borrow-btn"
                    onclick="borrowItem('${item.name}')"
                >
                    Borrow / Request
                </button>

                <button
                    class="contact-btn"
                    onclick="contactMember('${item.contact}')"
                >
                    Contact Member
                </button>

            </div>

        </div>

        `;

    });

}


function borrowItem(itemName){

    alert(
        "Request sent for: " +
        itemName +
        "\\nSAATH member will contact you."
    );

}


function contactMember(contact){

    alert(
        "Contact: " +
        contact
    );

}


displayResources();